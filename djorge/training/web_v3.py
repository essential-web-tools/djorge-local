"""Web-agent decision data v3 (built-in, procedurally generated, labels by explicit rules).

The decisions an agent like Jev asks a System-One model to make many times per task, in pt / en / es:

  browser_next     which page element to use next (decoys: sponsored items, disabled buttons, cookie walls, look-alikes)
  page_state       what happened after an action (success, error, login wall, captcha, out of stock, ...)
  injection        does web/tool content try to give instructions to the AI agent? (hard negatives: human-addressed
                   instructions, articles ABOUT prompt injection)
  url_trust        is a link legit, suspicious or phishing (look-alike domains, brand-in-subdomain, text/href mismatch)
  tool_select      which tool fits the request, or "none" when no listed tool fits (teaches principled abstention)
  plan_check       is a proposed tool call consistent with the user's request (wrong recipient, amount, scope, verb)
  evidence         does the retrieved snippet actually answer the question (near-miss attributes, other entity)
  next_step        continue / done / ask_user from goal + completed steps + missing information
  gate             allow / confirm / block for an agent action (verb x object x scope x environment rules)
  extract          extract a field (order id, total, tracking code, date, e-mail, CEP) or nothing if absent

Every value list and template list is split: templates with index % 5 == 4 and the held-out value lists are never
used for training, so validation/test measure NEW phrasings and NEW entities, not memorised strings.

    python -m djorge.training.web_v3 --out-dir DATA --train 2400 --test 120
writes  web_v3.jsonl (train + validation)  and  web_v3_test.jsonl (held-out, for benchmarks/broad_eval.py).
"""
