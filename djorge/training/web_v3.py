def browser_next(rng, n, held):
    P, out = Pools(held), []
    goals = [(i, g) for i, g in enumerate(BROWSER_GOALS) if _held(i) == held]
    for _ in range(n):
        gi, (lang, tpl, kind) = rng.choice(goals)
        p, other = P.pick(rng, *PRODUCTS), P.pick(rng, *PRODUCTS)
        site = P.pick(rng, *SITES)
        e = EL[lang]
        banner = rng.random() < 0.3
        disabled = kind == "add" and rng.random() < 0.3                  # size must be chosen first
        on_product = kind == "add" and rng.random() < 0.8
        cart_items = kind == "checkout" and rng.random() < 0.85
        items = {}
        def el(key, label, note=""):
            items[key] = f"{label}{note}"
        if banner:
            el("accept", e["accept"]); el("reject", e["reject"])
        if kind == "add":
            if on_product:
                el("add", e["add"], f" — {p}" + (" (disabled)" if disabled else ""))
                if disabled:
                    el("size", e["size"])
                el("sponsored", e["sponsored"], f" — {other}")
            else:
                el("search", e["search"]); el("sponsored", e["sponsored"], f" — {other}")
        elif kind == "search":
            el("search", e["search"]); el("sponsored", e["sponsored"], f" — {p}")
        else:
            el("cart", e["cart"]); el("checkout", e["checkout"] + ("" if cart_items else " (disabled)"))
        for k in rng.sample(["login", "blog", "privacy", "news"], 2):
            el(k, e[k])
        keys = list(items); rng.shuffle(keys)                         # element ids must not leak the answer
        ids = rng.sample(range(1, 40), len(keys))
        opts = {k: f"[e{i}] {items[k]}" for k, i in zip(keys, ids)}
        # rule-based gold
        if banner:
            gold = "reject"                                              # cookie wall first; privacy-preserving choice
        elif kind == "add":
            gold = ("size" if disabled else "add") if on_product else "search"
        elif kind == "search":
            gold = "search"
        else:
            gold = "checkout" if cart_items else "cart"
        state = {"en": "cookie banner is covering the page" if banner else "page loaded",
                 "pt": "banner de cookies cobrindo a página" if banner else "página carregada",
                 "es": "banner de cookies cubre la página" if banner else "página cargada"}[lang]
        if kind == "checkout" and not cart_items:
            state += {"en": "; the cart is not open yet", "pt": "; o carrinho ainda não foi aberto",
                      "es": "; el carrito aún no está abierto"}[lang]
        src = tpl.format(p=p) + "\n" + PAGE_HDR[lang].format(site=site, state=state)
        labels = list(opts.values()); rng.shuffle(labels)
        out.append(_rec("CHOICE", src, labels, opts[gold], "Which element should the browser use next?",
                        "browser_next", "", lang))
    return out


