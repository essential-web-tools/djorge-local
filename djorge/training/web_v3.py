def _lookalike(rng, dom):
    name, tld = dom.split(".", 1)
    tricks = [lambda: name.replace("a", "4", 1) + "." + tld if "a" in name else name + "-br." + tld,
              lambda: name.replace("l", "1", 1) + "." + tld if "l" in name else name + "1." + tld,
              lambda: f"{name}-seguranca.xyz", lambda: f"{name}-login.top", lambda: f"secure-{name}.com",
              lambda: f"{dom}.verify-account.ru", lambda: f"{name}.{tld}.atualizacao.online", lambda: f"{name}suporte.net"]
    return rng.choice(tricks)()


def url_trust(rng, n, held):
    out = []
    brands = BRANDS[1] if held else BRANDS[0]
    msgs = [m for i, m in enumerate(URL_MSG) if _held(i) == held]
    for _ in range(n):
        b, dom = rng.choice(brands)
        r = rng.random()
        path = rng.choice(["/login", "/conta", "/verify", "/invoice/2291", "/seguranca", ""])
        if r < 0.35:
            host = rng.choice([dom, "www." + dom, "login." + dom, "conta." + dom]); lab = "legit"
        elif r < 0.75:
            host = _lookalike(rng, dom); lab = "phishing"
        else:
            host = rng.choice(["bit.ly/3xK" + str(rng.randint(10, 99)), "tinyurl.com/a" + str(rng.randint(100, 999)),
                               "promo-ofertas.shop", "links.newsletter-mail.net"]); lab = "suspicious"; path = ""
        url = f"https://{host}{path}"
        shown = url
        if lab != "legit" and rng.random() < 0.4:                     # link text shows the real domain, href does not
            shown = f"[https://{dom}{path}]({url})"
            lab = "phishing"
        src = rng.choice(msgs).format(b=b, t=shown)
        opts = ["legit", "suspicious", "phishing"]; rng.shuffle(opts)
        out.append(_rec("CHOICE", src, opts, lab, "Is this link safe to open?", "url_trust", "", "?", URL_DESC))
    return out


