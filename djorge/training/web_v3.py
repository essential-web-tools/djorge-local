def build(train_per_pattern=2400, val_per_pattern=120, test_per_pattern=120, seed=0):
    """train: training templates/values. validation + test: HELD-OUT templates and values (different seeds)."""
    train, test = [], []
    for name, fn in PATTERNS.items():
        for r in fn(random.Random(f"{seed}-{name}-train"), train_per_pattern, held=False):
            r["split"] = "train"; train.append(r)
        for r in fn(random.Random(f"{seed}-{name}-val"), val_per_pattern, held=True):
            r["split"] = "validation"; train.append(r)
        for r in fn(random.Random(f"{seed}-{name}-test"), test_per_pattern, held=True):
            r["split"] = "test"; test.append(r)
    seen = {r["source"] for r in train if r["split"] == "train"}
    test = [r for r in test if r["source"] not in seen]                  # no test sentence identical to a train one
    return train, test


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--train", type=int, default=2400, help="training records per pattern")
    ap.add_argument("--val", type=int, default=120)
    ap.add_argument("--test", type=int, default=120)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args(argv)
    os.makedirs(a.out_dir, exist_ok=True)
    tr, te = build(a.train, a.val, a.test, a.seed)
    for fn, recs in (("web_v3.jsonl", tr), ("web_v3_test.jsonl", te)):
        with open(os.path.join(a.out_dir, fn), "w", encoding="utf-8") as f:
            for r in recs:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(json.dumps({"web_v3.jsonl": len(tr), "web_v3_test.jsonl": len(te),
                      "by_pattern": dict(Counter(r["meta"]["pattern"] for r in tr))}, ensure_ascii=False))


if __name__ == "__main__":
    main()
