def _held(i: int) -> bool:
    return i % 5 == 4


class Pools:
    """Value pools split into train / held-out halves."""

    def __init__(self, held: bool):
        self.held = held

    def pick(self, rng, train_vals, held_vals):
        return rng.choice(held_vals if self.held else train_vals)


