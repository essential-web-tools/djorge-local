def page_state(rng, n, held):
    out = []
    for _ in range(n):
        lab = rng.choice(STATES)
        txts = [(i, t) for i, t in enumerate(PAGE_TXT[lab]) if _held(i) == held] or list(enumerate(PAGE_TXT[lab]))[-1:]
        _, t = rng.choice(txts)
        body = t.format(n=rng.randint(2, 999))
        src = f"{rng.choice(NOISE)}\n{body}\n{rng.choice(NOISE)}" if rng.random() < 0.7 else body
        opts = rng.sample(STATES, 5)
        if lab not in opts:
            opts[0] = lab
        rng.shuffle(opts)
        out.append(_rec("CHOICE", "Page after the last action:\n" + src, opts, lab, "What is the state of the page?",
                        "page_state", "", "?", STATE_DESC))
