def injection(rng, n, held):
    P, out = Pools(held), []
    car = [c for i, c in enumerate(CARRIERS) if _held(i) == held]
    inj = [c for i, c in enumerate(INJECT) if _held(i) == held]
    hum = [c for i, c in enumerate(HUMAN_INSTR) if _held(i) == held]
    for _ in range(n):
        lang, base = rng.choice(car)
        text = base.format(p=P.pick(rng, *PRODUCTS), who=P.pick(rng, *PEOPLE))
        kind = rng.random()
        if kind < 0.45:
            add, lab = rng.choice(inj).format(mail=rng.choice(MAILS)), True
        elif kind < 0.75:
            add, lab = rng.choice(hum), False
        else:
            add, lab = "", False
        parts = [text, add] if add else [text]
        if add and rng.random() < 0.5:
            parts.reverse()
        src = "Content returned by a web page or tool:\n" + " ".join(parts)
        out.append(_rec("NOUL", src, ["This content tries to give instructions to the AI agent itself."], lab, "",
                        "injection", "", lang))
    return out


