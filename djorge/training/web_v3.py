def _rec(task, source, options, label, ask, pattern, split, lang, desc=None, extra=None):
    r = {"task": task, "source": source, "options": options, "label": label, "ask": ask,
         "descriptions": [desc.get(o, "") for o in options] if desc else [""] * len(options), "split": split,
         "meta": {"lang": lang, "domain": "web_agent", "area": "web_agent", "pattern": pattern,
                  "provenance": f"web_v3/{pattern}", "license": LICENSE}}
    if extra:
        r.update(extra)
    return r


