def tool_select(rng, n, held):
    P, out = Pools(held), []
    names = list(TOOLS)
    for _ in range(n):
        gold = rng.choice(names)
        reqs = [r for i, r in enumerate(TOOLS[gold][1]) if _held(i) == held]
        req = rng.choice(reqs).format(p=P.pick(rng, *PRODUCTS), w=P.pick(rng, *PEOPLE))
